import dotenv from "dotenv";
import path from "path";
import { Resend } from "resend";

// 1. Load Backend environment configuration
const envPath = path.resolve(__dirname, "../.env");
dotenv.config({ path: envPath });

async function main() {
  console.log("==================================================");
  console.log("       VLEARNN Resend API Integration Diagnostic   ");
  console.log("==================================================");

  const apiKey = process.env.RESEND_API_KEY?.trim();
  const fromEmail = process.env.EMAIL_FROM?.trim() || "VLEARNN Admissions <onboarding@resend.dev>";
  const adminEmail = process.env.ADMIN_NOTIFICATION_EMAIL?.trim();

  // 2. Validate configuration without exposing secrets
  console.log("\n[Step 1: Configuration Check]");
  console.log(`- Backend .env Path: ${envPath}`);
  
  if (!apiKey) {
    console.error("❌ FAILURE: RESEND_API_KEY is missing or empty in Backend/.env.");
    process.exit(1);
  }

  const plausibleFormat = apiKey.startsWith("re_") && apiKey.length >= 20;
  console.log(`- RESEND_API_KEY Present: Yes (Length: ${apiKey.length} characters)`);
  console.log(`- Key Format Plausible: ${plausibleFormat ? "Yes (Valid prefix 're_')" : "No (Expected prefix 're_')"}`);
  
  if (!plausibleFormat) {
    console.error("❌ FAILURE: RESEND_API_KEY does not appear to be a valid Resend API key.");
    process.exit(1);
  }

  if (!fromEmail) {
    console.error("❌ FAILURE: EMAIL_FROM is not configured.");
    process.exit(1);
  }
  console.log(`- Sender Address (EMAIL_FROM): ${fromEmail}`);

  if (!adminEmail || !adminEmail.includes("@")) {
    console.error("❌ FAILURE: ADMIN_NOTIFICATION_EMAIL is missing or not a valid email address.");
    process.exit(1);
  }
  console.log(`- Admin Recipient (ADMIN_NOTIFICATION_EMAIL): ${adminEmail}`);

  // 3. Initialize Resend SDK
  console.log("\n[Step 2: Resend SDK Initialization]");
  let resend: Resend;
  try {
    resend = new Resend(apiKey);
    console.log("✔ Resend client initialized successfully.");
  } catch (err: any) {
    console.error("❌ FAILURE: Failed to initialize Resend SDK:", err?.message || err);
    process.exit(1);
  }

  // 4. Send exactly ONE diagnostic email
  console.log("\n[Step 3: Sending Single Diagnostic Verification Email]");
  console.log(`- Dispatching test email to: ${adminEmail}`);
  console.log(`- Using sender: ${fromEmail}`);

  const timestamp = new Date().toISOString();
  const subject = `[VLEARNN Diagnostic] Resend API Verification - ${timestamp}`;

  try {
    const response = await resend.emails.send({
      from: fromEmail,
      to: [adminEmail],
      subject,
      text: `This is a single automated verification test for the VLEARNN platform.
Timestamp: ${timestamp}
Sender: ${fromEmail}
Recipient: ${adminEmail}
Status: API request accepted by Resend provider.`,
      html: `
        <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #E5E9F0; border-radius: 6px;">
          <h2 style="color: #172B4D; margin-top: 0;">VLEARNN Resend Integration Test</h2>
          <p style="color: #496A8A; font-size: 14px;">This email confirms that the VLEARNN backend has successfully authenticated with the Resend API and dispatched a verified notification.</p>
          <div style="background-color: #F7F6F2; padding: 12px 16px; border-left: 4px solid #C88B3A; margin: 16px 0; font-size: 13px;">
            <strong>Verification Details:</strong><br/>
            • <strong>Timestamp:</strong> ${timestamp}<br/>
            • <strong>Configured Sender:</strong> ${fromEmail}<br/>
            • <strong>Notification Target:</strong> ${adminEmail}<br/>
            • <strong>Provider:</strong> Resend Official Node.js SDK
          </div>
          <p style="font-size: 12px; color: #7493B3; margin-bottom: 0;">Automated health test generated by VLEARNN diagnostics suite.</p>
        </div>
      `,
    });

    if (response.error) {
      console.error("\n❌ RESEND API ERROR REJECTED REQUEST:");
      console.error(`- Error Name: ${response.error.name}`);
      console.error(`- Error Message: ${response.error.message}`);
      
      if (response.error.message.includes("testing emails to your own email")) {
        console.warn("\nℹ DOMAIN NOTE:");
        console.warn("When sending from onboarding@resend.dev, Resend free accounts can only send emails to the address used to create the Resend account.");
        console.warn(`If ${adminEmail} is not your Resend account email, either change ADMIN_NOTIFICATION_EMAIL in Backend/.env to your registered Resend email, or verify a custom domain in the Resend dashboard (https://resend.com/domains).`);
      }
      process.exit(1);
    }

    if (response.data && response.data.id) {
      console.log("\n✔ SUCCESS: Resend API accepted the email dispatch request!");
      console.log(`- Provider Message ID: ${response.data.id}`);
      console.log("- Status: Dispatched (API Accepted)");
      console.log(`- Delivery Notice: The email has been queued for delivery to ${adminEmail}.`);
      console.log("==================================================");
      return;
    } else {
      console.error("❌ UNEXPECTED RESPONSE: Resend API did not return a message ID or error:", response);
      process.exitCode = 1;
      return;
    }
  } catch (networkError: any) {
    console.error("\n❌ NETWORK OR REQUEST EXCEPTION:");
    console.error(`- Message: ${networkError?.message || networkError}`);
    process.exit(1);
  }
}

main().catch((err) => {
  console.error("Fatal diagnostic error:", err?.message || err);
  process.exit(1);
});
